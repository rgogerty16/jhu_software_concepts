def _bestfit(x, y):
    """Return (xs, ys, label) for a degree-1 NumPy least-squares fit."""
    coeffs = np.polyfit(x, y, 1)
    xs = np.linspace(np.min(x), np.max(x), 100)
    ys = np.polyval(coeffs, xs)
    label = f"best-fit: y = {coeffs[0]:.2f}x + {coeffs[1]:.2f}"
    return xs, ys, label


def scatter_gre_vs_grev(df, path):
    """Scatter of non-zero GRE vs GRE V with a NumPy best-fit line."""
    sub = df[(df["GRE"] > 0) & (df["GRE V"] > 0)][["GRE", "GRE V"]].dropna()
    x, y = sub["GRE"].to_numpy(), sub["GRE V"].to_numpy()
    fig, ax = plt.subplots(figsize=(8, 6))
    ax.scatter(x, y, s=14, alpha=0.5, color="#2b6cb0", label="applicants")
    if len(sub) >= 2:
        xs, ys, lbl = _bestfit(x, y)
        ax.plot(xs, ys, color="#c53030", lw=2, label=lbl)
    ax.set_title("GRE (Quant) vs GRE Verbal")
    ax.set_xlabel("GRE Quantitative (130-170 scale)")
    ax.set_ylabel("GRE Verbal (130-170 scale)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path



# Analytical summary PDF (assignment section 8)
# --------------------------------------------------------------------------- #
def _pdf_page(pdf, title, body):
    """Render one text page (title + wrapped body) into ``pdf``."""
    fig = plt.figure(figsize=(8.5, 11))
    fig.text(0.08, 0.94, title, fontsize=15, fontweight="bold", va="top")
    wrapped = []
    for para in body.split("\n"):
        wrapped.extend(textwrap.wrap(para, width=95) or [""])
    fig.text(0.08, 0.88, "\n".join(wrapped), fontsize=10.5, va="top", family="monospace")
    plt.axis("off")
    pdf.savefig(fig)
    plt.close(fig)


def build_analytics_pdf(path, stats):
    """Write ``analytics.pdf`` from a dict of code-computed ``stats``.

    Every number in the prose comes from ``stats`` (computed in the notebook),
    so nothing is hard-coded -- the PDF interprets values the cleaning pipeline
    produced.
    """
    with PdfPages(path) as pdf:
        _pdf_page(pdf, "Module 8 -- Grad Cafe: Analytical Summary", (
            "This report summarizes the cleaned Grad Cafe dataset and the SciPy\n"
            "statistical analyses run in module_8.ipynb. All figures are generated\n"
            "by code from the cleaned DataFrame; the text interprets them.\n\n"
            f"Cleaned dataset: {stats['clean_rows']:,} rows x {stats['clean_cols']} columns "
            f"(from {stats['raw_rows']:,} raw rows).\n\n"
            "Q1. Average GRE of accepted PhD applicants\n"
            f"    -> {stats['avg_gre_accepted_phd']} "
            f"(n = {stats['n_gre_accepted_phd']} applicants with a valid GRE).\n\n"
            "Q2. Average GPA of accepted Master's applicants\n"
            f"    -> {stats['avg_gpa_accepted_masters']} "
            f"(n = {stats['n_gpa_accepted_masters']} applicants with a valid GPA).\n"
            "    Both averages use only valid, non-missing scores, so they describe\n"
            "    the reporting subset rather than every accepted applicant."
        ))

        _pdf_page(pdf, "Q3. Shortcomings of inferring decision_date", (
            "decision_date is inferred from a free-text status/notification field plus\n"
            "the term year. Key shortcomings:\n\n"
            "1. Ambiguous / missing year. The notification text carries only a month and\n"
            "   day (e.g. 'Feb 10'); we borrow the year from the term (e.g. Fall 2026).\n"
            "   Decisions that actually land in the calendar year before or after the\n"
            "   term are dated incorrectly, which can even make days_to_decision negative.\n\n"
            "2. Free-text fragility. Users type statuses inconsistently ('Interview' vs\n"
            "   'Interviewed', extra words, typos, blanks). Any format we did not\n"
            "   anticipate is silently dropped to a missing date.\n\n"
            "3. No timezone / self-reported lag. Dates are entered by applicants after\n"
            "   the fact, so they approximate rather than record the true decision date;\n"
            "   day-level precision is optimistic."
        ))

        _pdf_page(pdf, "Q4-Q6. Statistical analyses", (
            "Q4. Correlation between GPA and GRE-related measures.\n"
            f"    Pearson GRE vs GRE V: r = {stats['gre_grev_r']}, "
            f"p = {stats['gre_grev_p']} (n = {stats['gre_grev_n']}).\n"
            f"    GPA vs GRE ({stats['gpa_gre_method']}): r = {stats['gpa_gre_r']}, "
            f"p = {stats['gpa_gre_p']} (n = {stats['gpa_gre_n']}).\n"
            f"    {stats['corr_interpretation']}\n\n"
            "Q5. Group comparison of GPA (Accepted vs Rejected).\n"
            f"    Test: {stats['group_test']}; statistic = {stats['group_stat']}, "
            f"p = {stats['group_p']}.\n"
            f"    Accepted mean GPA = {stats['accepted_gpa_mean']} "
            f"(n = {stats['accepted_gpa_n']}); "
            f"Rejected mean GPA = {stats['rejected_gpa_mean']} "
            f"(n = {stats['rejected_gpa_n']}).\n"
            f"    {stats['group_interpretation']}\n\n"
            "Q6. Chi-square: Degree vs US/International.\n"
            f"    chi2 = {stats['chi2_stat']}, p = {stats['chi2_p']}, "
            f"dof = {stats['chi2_dof']}.\n"
            f"    {stats['chi2_interpretation']}"
        ))

        _pdf_page(pdf, "Q7. Remaining data-quality issues", (
            "Even after cleaning, several issues remain:\n\n"
            "* Sparse GRE reporting. Only a small minority of rows carry any GRE score,\n"
            "  so every GRE statistic describes a self-selected reporting subset.\n\n"
            "* Residual out-of-range values. Some GPAs sit outside 0-4.0 (e.g. 10-point\n"
            "  or percentage scales); has_valid_gpa flags but does not repair them.\n\n"
            "* Self-reported, unverified entries. Programs, universities, and outcomes are\n"
            "  free text; near-duplicate spellings survive standardization.\n\n"
            "* Inferred, sometimes-negative days_to_decision from the date logic in Q3.\n\n"
            "* Class imbalance. Terms and outcomes are dominated by a single value, which\n"
            "  limits how far group comparisons generalize.\n\n"
            "Takeaway: the dataset is now analysis-ready for descriptive EDA, but the\n"
            "numbers should be read as patterns in self-reported data, not ground truth."
        ))
    return path

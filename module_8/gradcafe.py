def bar_degree_by_international(df, path):
    """Grouped bar chart: Degree counts broken down by US/International."""
    ct = pd.crosstab(df["Degree"], df["US/International"])
    fig, ax = plt.subplots(figsize=(8, 6))
    ct.plot(kind="bar", ax=ax)
    ax.set_title("Applicants by Degree, split by US/International")
    ax.set_xlabel("Degree")
    ax.set_ylabel("Number of applicants (count)")
    ax.tick_params(axis="x", rotation=0)
    ax.legend(title="US/International")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def hist_acceptances_over_time(df, path):
    """Histogram of Accepted applicants by decision_date in 3-day bins."""
    dates = df.loc[df["outcome"] == "Accepted", "decision_date"].dropna()
    fig, ax = plt.subplots(figsize=(9, 6))
    if len(dates):
        nums = mdates.date2num(dates)
        bins = np.arange(nums.min(), nums.max() + 3, 3)  # 3-day-wide bins
        ax.hist(nums, bins=bins, color="#2b6cb0", edgecolor="white", label="acceptances")
        ax.xaxis_date()
        fig.autofmt_xdate()
    ax.set_title("Acceptances over time (3-day bins)")
    ax.set_xlabel("Decision date")
    ax.set_ylabel("Number of acceptances (count)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def box_gpa_by_outcome(df, path):
    """Boxplot of GPA distribution grouped by outcome."""
    order = ["Accepted", "Rejected", "Waitlisted", "Interviewed"]
    present = [o for o in order if o in df["outcome"].unique()]
    data = [df.loc[(df["outcome"] == o) & (df["GPA"].between(0, 4.0)), "GPA"].dropna()
            for o in present]
    fig, ax = plt.subplots(figsize=(8, 6))
    ax.boxplot(data, labels=present, showfliers=True)
    ax.set_title("GPA distribution by outcome")
    ax.set_xlabel("Outcome")
    ax.set_ylabel("GPA (4.0 scale)")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def correlation_heatmap(df, path, cols=("GPA", "GRE", "GRE V", "GRE AW")):
    """Correlation heatmap for the numeric columns."""
    corr = df[list(cols)].corr()
    fig, ax = plt.subplots(figsize=(7, 6))
    im = ax.imshow(corr.to_numpy(), vmin=-1, vmax=1, cmap="coolwarm")
    ax.set_xticks(range(len(cols)))
    ax.set_yticks(range(len(cols)))
    ax.set_xticklabels(cols, rotation=45, ha="right")
    ax.set_yticklabels(cols)
    for i in range(len(cols)):
        for j in range(len(cols)):
            ax.text(j, i, f"{corr.iloc[i, j]:.2f}", ha="center", va="center",
                    color="black")
    ax.set_title("Numeric correlation heatmap")
    fig.colorbar(im, ax=ax, label="Pearson r")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path



# Rendering DataFrames / Series to PNG (the "screenshot" deliverables)
# --------------------------------------------------------------------------- #
def _truncate(value, width=22):
    """Shorten a cell value so wide tables stay legible in a PNG."""
    text = "" if value is None else str(value)
    return text if len(text) <= width else text[: width - 1] + "…"


def render_table_png(frame, path, title=None, max_rows=5, index=True):
    """Save ``frame`` (DataFrame or Series) as a table image at ``path``.

    Only the first ``max_rows`` rows are drawn. This is the code-generated
    stand-in for a manual screenshot, so the image deliverables are reproducible.
    """
    if isinstance(frame, pd.Series):
        frame = frame.to_frame()
    view = frame.head(max_rows).copy()

    col_labels = [str(c) for c in view.columns]
    cell_text = [[_truncate(v) for v in row] for row in view.itertuples(index=False)]
    if index:
        col_labels = [""] + col_labels
        cell_text = [[_truncate(idx)] + row for idx, row in zip(view.index, cell_text)]

    n_cols = max(len(col_labels), 1)
    fig_w = min(2 + 1.5 * n_cols, 26)
    fig_h = 1.2 + 0.45 * (len(cell_text) + 1)
    fig, ax = plt.subplots(figsize=(fig_w, fig_h))
    ax.axis("off")
    if title:
        ax.set_title(title, fontweight="bold", pad=12)

    table = ax.table(cellText=cell_text or [[""]], colLabels=col_labels,
                     cellLoc="left", loc="center")
    table.auto_set_font_size(False)
    table.set_fontsize(8)
    table.scale(1, 1.4)
    for (r, _c), cell in table.get_celld().items():
        if r == 0:
            cell.set_text_props(fontweight="bold", color="white")
            cell.set_facecolor("#40466e")
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    return path


